export const propertyById = (id: string): Property | undefined =>
  properties.find((p) => p.id === id)

/** Every comune that currently has stock, alphabetical — drives the filter bar. */
export const comuni: string[] = [...new Set(properties.map((p) => p.comune))].sort((a, b) =>
  a.localeCompare(b, 'it'),
)

export const priceRange = (contratto: 'vendita' | 'affitto'): [number, number] => {
  const p = properties.filter((x) => x.contratto === contratto).map((x) => x.prezzo)
  return [Math.min(...p), Math.max(...p)]
}
